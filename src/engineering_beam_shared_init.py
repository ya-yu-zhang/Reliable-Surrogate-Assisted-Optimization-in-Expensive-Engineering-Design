"""Matched-initialization GP-EI and TuRBO-1 beam experiment.

The first 2D+20 observations are read from the completed internal-method
beam logs. They count toward the algorithm budget but are not physically
queried again. All subsequent proposals are generated by the external
method itself and evaluated by the finite-element objective.
"""
