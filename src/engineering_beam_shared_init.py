ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "configs/engineering_beam_shared_init.json"
AUTHOR = ROOT / "literature/source-code/TuRBO"


def file_sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def code_hash():
    h = hashlib.sha256()
    for path in [Path(__file__), ROOT / "src/core.py", ROOT / "src/engineering_beam_adapter.py",
                 ROOT / "src/gp_references.py"]:
        h.update(str(path.relative_to(ROOT)).replace("\\", "/").encode())
        h.update(path.read_bytes())
    for name in ["turbo_1.py", "gp.py", "utils.py", "__init__.py"]:
        path = AUTHOR / "turbo" / name
        h.update(name.encode())
        h.update(path.read_bytes())
    return h.hexdigest()


def _read_events(path):
    return [json.loads(line) for line in Path(path).read_text("utf-8").splitlines() if line.strip()]


def shared_archive(rep, cfg=None):
    cfg = cfg or json.loads(CONFIG.read_text("utf-8"))
    source = ROOT / cfg["source"]
    dim, budget = cfg["dimension"], cfg["budget"]
    runid = f"PEM_T_f01_d{dim}_i1_r{rep}_b{budget}"
    source_log = source / "PEM_T" / runid / "events.jsonl"
    events = _read_events(source_log)
    pre = {e["t"]: e for e in events if e.get("event") == "pre"}
    labels = {e["t"]: e for e in events if e.get("event") == "label"}
    n0 = cfg["shared_initial_evaluations"]
    points = np.array([pre[t]["x"] for t in range(1, n0 + 1)], dtype=float)
    values = np.array([labels[t]["y"] for t in range(1, n0 + 1)], dtype=float)
    expected = init_design(dim, 100000 * dim + 1000 + 10 + rep)
    if points.shape != (n0, dim) or not np.array_equal(points, expected):
        raise AssertionError(f"shared design mismatch for repeat {rep}")
    if not np.isfinite(values).all():
        raise AssertionError(f"nonfinite shared labels for repeat {rep}")
    digest = hashlib.sha256()
    digest.update(points.tobytes())
    digest.update(values.tobytes())
    return points, values, digest.hexdigest(), source_log


def audit_shared_sources(cfg=None):
    cfg = cfg or json.loads(CONFIG.read_text("utf-8"))
    source = ROOT / cfg["source"]
    checked = []
    for rep in range(cfg["repeats"]):
        points, values, digest, _ = shared_archive(rep, cfg)
        for method in ["greedy", "fixed01", "PEM_T"]:
            runid = f"{method}_f01_d{cfg['dimension']}_i1_r{rep}_b{cfg['budget']}"
            events = _read_events(source / method / runid / "events.jsonl")
            pre = [e for e in events if e.get("event") == "pre"][:len(points)]
            labels = [e for e in events if e.get("event") == "label"][:len(values)]
            if not np.array_equal(np.array([e["x"] for e in pre]), points):
                raise AssertionError(f"initial points differ: {method}, repeat {rep}")
            if not np.array_equal(np.array([e["y"] for e in labels]), values):
                raise AssertionError(f"initial labels differ: {method}, repeat {rep}")
        checked.append({"rep": rep, "count": len(values), "archive_sha256": digest,
                        "best": float(values.min())})
    return checked


def inject_shared_archive(oracle, points, values, source_digest):
    for index, (point, value) in enumerate(zip(points, values), start=1):
        oracle.state = lambda index=index: {
            "mode": "shared_initial_archive", "index": index - 1,
            "source_archive_sha256": source_digest, "reused_label": True,
        }
        oracle.write({"event": "pre", "t": index, "n_observed": index - 1,
                      "x": point.tolist(), "x_unit": point.tolist(),
                      "best_before": min(oracle.values) if oracle.values else None,
                      "optimizer_state": oracle.state(), "preparation_seconds": 0.0})
        oracle.points.append(point.copy())
        oracle.values.append(float(value))
        oracle.write({"event": "label", "t": index, "y": float(value),
                      "best_after": min(oracle.values), "reused_label": True})
    oracle.last_end = perf_counter()


def expected_improvement(mu, sd, best):
    mu, sd = np.asarray(mu), np.asarray(sd)
    improvement = best - mu
    z = np.divide(improvement, sd, out=np.zeros_like(improvement), where=sd > 1e-15)
    return np.where(sd > 1e-15, improvement * norm.cdf(z) + sd * norm.pdf(z),
                    np.maximum(improvement, 0))


def probability_improvement(mu, sd, best, xi):
    """Probability of improving on ``best`` by at least ``xi``."""
    mu, sd = np.asarray(mu), np.asarray(sd)
    improvement = best - xi - mu
    z = np.divide(improvement, sd, out=np.zeros_like(improvement), where=sd > 1e-15)
    return np.where(sd > 1e-15, norm.cdf(z), (improvement > 0).astype(float))


def _gp_acquisition_after_shared(oracle, dim, seed, acquisition_name):
    """Run a matched-history GP acquisition with a common model and search budget."""
    if acquisition_name not in {"ei", "pi", "ucb"}:
        raise ValueError(acquisition_name)
    kernel = ConstantKernel(1., (.05, 20)) * Matern(np.full(dim, .2), (.005, 2.), nu=2.5)
    while len(oracle.values) < oracle.budget:
        t = len(oracle.values) + 1
        xx = (np.array(oracle.points) - oracle.lb) / (oracle.ub - oracle.lb)
        yy = np.array(oracle.values)
        model = GaussianProcessRegressor(kernel=kernel, alpha=1e-6, normalize_y=True,
                                         n_restarts_optimizer=0, random_state=seed)
        model.fit(xx, yy)
        kernel = model.kernel_
        sequence = qmc.Sobol(dim, scramble=True,
                             seed=np.random.default_rng(np.random.SeedSequence([seed, 721, t]))).random_base2(12)
        sequence = sequence[cdist(sequence, xx).min(axis=1) >= 1e-10]
        if not len(sequence):
            raise RuntimeError(f"No distinct GP-{acquisition_name.upper()} candidates")

        xi = 0.01 * (float(yy.std()) if yy.std() > 0 else 1.0)
        kappa = 2.0

        def score(mean, std):
            if acquisition_name == "ei":
                return expected_improvement(mean, std, yy.min())
            if acquisition_name == "pi":
                return probability_improvement(mean, std, yy.min(), xi)
            # For minimization, maximizing this score is equivalent to minimizing
            # the lower confidence bound mean - kappa * standard deviation.
            return -(np.asarray(mean) - kappa * np.asarray(std))

        mu, sd = model.predict(sequence, return_std=True)
        scores = score(mu, sd)
        candidates = list(sequence)

        def acquisition(point):
            mean, std = model.predict(np.array([point]), return_std=True)
            return -float(score(mean, std)[0])

        for index in np.argsort(-scores, kind="stable")[:8]:
            result = minimize(acquisition, sequence[index], method="L-BFGS-B",
                              bounds=[(0, 1)] * dim, options={"maxiter": 50})
            if (np.isfinite(result.x).all() and np.all((result.x >= 0) & (result.x <= 1))
                    and cdist(np.array([result.x]), xx).min() >= 1e-10):
                candidates.append(result.x)
        candidates = np.array(candidates)
        mu, sd = model.predict(candidates, return_std=True)
        scores = score(mu, sd)
        fallback = bool(np.all(~np.isfinite(scores)))
        index = int(np.argmax(sd if fallback else scores))
        state = {"mode": f"gp_{acquisition_name}" if not fallback else "variance_fallback",
                 "mu": float(mu[index]), "sd": float(sd[index]),
                 "acquisition_score": float(scores[index]),
                 "xi": xi if acquisition_name == "pi" else None,
                 "kappa": kappa if acquisition_name == "ucb" else None,
                 "kernel_theta": kernel.theta.tolist(), "training_count": len(yy),
                 "training_mean": float(yy.mean()),
                 "training_scale": float(yy.std()) if yy.std() > 0 else 1.,
                 "acquisition_candidates": len(candidates), "continuous_starts": 8,
                 "shared_initialization": True}
        oracle.state = lambda state=state: state
        oracle(oracle.lb + (oracle.ub - oracle.lb) * candidates[index])


def gp_ei_after_shared(oracle, dim, seed):
    return _gp_acquisition_after_shared(oracle, dim, seed, "ei")


def gp_pi_after_shared(oracle, dim, seed):
    return _gp_acquisition_after_shared(oracle, dim, seed, "pi")


def gp_ucb_after_shared(oracle, dim, seed):
    return _gp_acquisition_after_shared(oracle, dim, seed, "ucb")


def turbo_after_shared(oracle, dim):
    import sys
    sys.path.insert(0, str(AUTHOR))
    from turbo import Turbo1
    from turbo.utils import from_unit_cube, latin_hypercube, to_unit_cube

    optimizer = Turbo1(f=oracle, lb=oracle.lb, ub=oracle.ub, n_init=2 * dim,
                       max_evals=oracle.budget, batch_size=1, verbose=False, use_ard=True,
                       n_training_steps=50, max_cholesky_size=2000, min_cuda=1024,
                       device="cpu", dtype="float64")
    initial_x = np.array(oracle.points)
    initial_y = np.array(oracle.values)[:, None]
    optimizer.n_evals = len(initial_y)
    optimizer._X = deepcopy(initial_x)
    optimizer._fX = deepcopy(initial_y)
    optimizer.X = deepcopy(initial_x)
    optimizer.fX = deepcopy(initial_y)
    oracle.state = lambda: {"mode": "turbo_author", "optimizer_evaluations": optimizer.n_evals,
                            "trust_region_length": float(optimizer.length),
                            "trust_region_observed": len(optimizer._fX),
                            "n_init": optimizer.n_init, "candidate_count": optimizer.n_cand,
                            "shared_initialization": True}
    stopped = False
    try:
        while optimizer.n_evals < optimizer.max_evals:
            while optimizer.n_evals < optimizer.max_evals and optimizer.length >= optimizer.length_min:
                x_unit = to_unit_cube(deepcopy(optimizer._X), optimizer.lb, optimizer.ub)
                f_values = deepcopy(optimizer._fX).ravel()
                candidates, sampled, _ = optimizer._create_candidates(
                    x_unit, f_values, length=optimizer.length,
                    n_training_steps=optimizer.n_training_steps, hypers={})
                x_next = from_unit_cube(optimizer._select_candidates(candidates, sampled),
                                        optimizer.lb, optimizer.ub)
                f_next = np.array([[optimizer.f(x)] for x in x_next])
                optimizer._adjust_length(f_next)
                optimizer.n_evals += optimizer.batch_size
                optimizer._X = np.vstack((optimizer._X, x_next))
                optimizer._fX = np.vstack((optimizer._fX, f_next))
                optimizer.X = np.vstack((optimizer.X, deepcopy(x_next)))
                optimizer.fX = np.vstack((optimizer.fX, deepcopy(f_next)))
            if optimizer.n_evals >= optimizer.max_evals:
                break
            optimizer._restart()
            x_init = from_unit_cube(latin_hypercube(optimizer.n_init, optimizer.dim),
                                    optimizer.lb, optimizer.ub)
            f_init = []
            for point in x_init:
                f_init.append([optimizer.f(point)])
            f_init = np.array(f_init)
            optimizer.n_evals += optimizer.n_init
            optimizer._X, optimizer._fX = deepcopy(x_init), deepcopy(f_init)
            optimizer.X = np.vstack((optimizer.X, deepcopy(x_init)))
            optimizer.fX = np.vstack((optimizer.fX, deepcopy(f_init)))
    except BudgetExhausted:
        stopped = True
    return {"budget_guard_triggered": stopped,
            "author_internal_evaluations": optimizer.n_evals,
            "author_archive_labels": len(optimizer.fX),
            "external_archive_labels": len(oracle.values)}


def run_one(method, rep, cfg=None):
    cfg = cfg or json.loads(CONFIG.read_text("utf-8"))
    dim, budget = cfg["dimension"], cfg["budget"]
    seed = 100000 * dim + 1000 + 10 + rep
    runid = f"{method}_f01_d{dim}_i1_r{rep}_b{budget}"
    directory = ROOT / cfg["out"] / method / runid
    directory.mkdir(parents=True, exist_ok=True)
    points, values, archive_digest, source_log = shared_archive(rep, cfg)
    signature = {"fid": 1, "dim": dim, "instance": 1, "rep": rep,
                 "method": method, "budget": budget, "seed": seed,
                 "code_hash": code_hash(), "source_archive_sha256": archive_digest,
                 "source_log_sha256": file_sha256(source_log),
                 "shared_initial_evaluations": len(values),
                 "packages": {p: importlib.metadata.version(p) for p in
                              ["numpy", "scipy", "torch", "gpytorch", "scikit-learn"]}}
    summary_path = directory / "summary.json"
    if summary_path.exists():
        result = json.loads(summary_path.read_text("utf-8"))
        if result["signature"] != signature:
            raise RuntimeError(f"stale result: {directory}")
        return result
    objective = make_problem()
    np.random.seed(seed)
    torch.manual_seed(seed)
    warning_counts = Counter()
    original_show = warnings.showwarning
    started = perf_counter()
    with (directory / "events.jsonl").open("w", encoding="utf-8") as journal, warnings.catch_warnings():
        warnings.simplefilter("always")

        def count_warning(message, category, filename, lineno, file=None, line=None):
            warning_counts[category.__name__ + ": " + str(message)[:180]] += 1

        warnings.showwarning = count_warning
        oracle = BudgetJournal(objective, budget, objective.bounds.lb, objective.bounds.ub, journal)
        oracle.write({"event": "meta", **signature, "schema": 1,
                      "author_commit": "de0db39f481d9505bb3610b7b7aa0ebf7702e4a5"
                      if method.startswith("turbo") else None})
        inject_shared_archive(oracle, points, values, archive_digest)
        try:
            if method.startswith("turbo"):
                extra = turbo_after_shared(oracle, dim)
            elif method.startswith("gp_pi"):
                extra = gp_pi_after_shared(oracle, dim, seed) or {}
            elif method.startswith("gp_ucb"):
                extra = gp_ucb_after_shared(oracle, dim, seed) or {}
            else:
                extra = gp_ei_after_shared(oracle, dim, seed) or {}
        finally:
            warnings.showwarning = original_show
    if len(oracle.values) != budget:
        raise AssertionError("algorithm budget mismatch")
    expected_physical = budget - len(values)
    if objective.state.evaluations != expected_physical:
        raise AssertionError("physical objective counter mismatch")
    result = {"signature": signature, "runid": runid,
              "algorithm_evaluations": budget,
              "reused_initial_evaluations": len(values),
              "new_physical_evaluations": objective.state.evaluations,
              "best": min(oracle.values), "error": min(oracle.values),
              "initial_best": float(values.min()),
              "normalized_error": float(min(oracle.values) / values.min()),
              "elapsed": perf_counter() - started,
              "objective_seconds": oracle.objective_seconds,
              "preparation_seconds": oracle.prepare_seconds,
              "process_peak_working_set_bytes": memory_peak(),
              "exact_duplicate_calls": budget - len(np.unique(np.array(oracle.points), axis=0)),
              "warning_counts": dict(warning_counts), **extra}
    summary_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result
