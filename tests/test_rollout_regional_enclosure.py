"""Necessary mathematical checks for the new certificate transformation."""
import math
import unittest
from fractions import Fraction
from scipy.integrate import quad
from scipy.special import ndtr
from src.rollout_v2_intervals import I
from src.rollout_regional_enclosure import (
    capped_first_moment, baseline, regional_enclosure, weighted_stability_radius)


class RegionalTests(unittest.TestCase):
    def model(self, m=0., s=1., m0=1.):
        return dict(initial=m0, first_mean=m, first_sd=s)

    def test_capped_moment_against_independent_integral(self):
        for m,s,m0,lo,hi in [(0.,1.,1.,-9.,9.), (1.,.7,2.,-3.,.2),
                              (-2.,1.3,.4,-.7,5.), (2.,.4,3.,-8.,8.)]:
            model=self.model([m-1e-9,m+1e-9],[s-1e-9,s+1e-9],m0)
            interval=capped_first_moment(model,lo,hi)
            for mm,ss in [(m,s),(m-1e-9,s+1e-9),(m+1e-9,s-1e-9)]:
                cross=(math.log(m0)-mm)/ss
                value,error=quad(lambda x:min(m0,math.exp(mm+ss*x))*
                    math.exp(-x*x/2)/math.sqrt(2*math.pi),lo,hi,
                    points=[cross] if lo<cross<hi else None,epsabs=1e-12,epsrel=1e-12)
                self.assertLessEqual(interval.lo,value+error)
                self.assertGreaterEqual(interval.hi,value-error)

    def test_analytic_whole_line_and_low_tail(self):
        model=self.model()
        # h=min(1,exp(X)); completing the square gives exp(1/2)Phi(-1)+1/2.
        exact=math.exp(.5)*ndtr(-1)+.5
        interval=capped_first_moment(model)
        self.assertLessEqual(interval.lo,exact+1e-15)
        self.assertGreaterEqual(interval.hi,exact-1e-15)
        self.assertLessEqual(baseline(model).lo,1-exact+1e-15)
        self.assertEqual(capped_first_moment(model,1,1).pair(),[0.,0.])
        # Instability only below eps: H_E <= eps P(E), much smaller than P(E).
        eps=.01
        domain=(Fraction(eps),None)
        old=ndtr(math.log(eps))
        radius=weighted_stability_radius(model,domain,old)
        self.assertLessEqual(radius,eps*old*(1+1e-12))

    def test_conversion_contains_known_fixed_value(self):
        model=self.model()
        # q(x)=1-h(x)/2 is a synthetic valid conditional reward in [1-h,1].
        # Its leaf integrals are generated by an independent numerical oracle.
        leaves=[]
        for low,high in [(-8.,-1.),(-1.,0.),(0.,1.),(1.,8.)]:
            v,e=quad(lambda x:(1-min(1,math.exp(x))/2)*
                math.exp(-x*x/2)/math.sqrt(2*math.pi),low,high,epsabs=1e-13,epsrel=1e-13)
            leaves.append(dict(low=low,high=high,active=[0],interval=[v-e-1e-13,v+e+1e-13]))
        cert=dict(fixed=0,leaves=leaves)
        exact=1-(math.exp(.5)*ndtr(-1)+.5)/2
        # Partial leaf restrictions and outward uncertain response endpoints.
        for domain in [(Fraction(1,2),Fraction(2)),(Fraction(0),None),None]:
            result=regional_enclosure(model,domain,cert,[0.,1.])
            self.assertLessEqual(result['interval'][0],exact)
            self.assertGreaterEqual(result['interval'][1],exact)
        all_stable=regional_enclosure(model,(Fraction(0),None),cert,[0.,1.])
        self.assertLess(all_stable['interval'][1]-all_stable['interval'][0],1e-10)

    def test_invalid_cover_or_nonfixed_certificate_rejected(self):
        with self.assertRaises(ArithmeticError):
            regional_enclosure(self.model(),None,dict(fixed=0,leaves=[]),[0.,1.])
        with self.assertRaises(ValueError):
            regional_enclosure(self.model(),None,dict(fixed=None),[0.,1.])
        with self.assertRaises(ArithmeticError):
            capped_first_moment(self.model(s=[0.,1.]))


if __name__=='__main__':
    unittest.main()
